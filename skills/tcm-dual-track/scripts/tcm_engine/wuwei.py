@dataclass
class HerbTiYong:
    ti: float
    yong: float


@dataclass
class HerbData:
    五味: List[str] = field(default_factory=list)
    性: str = ""
    归经: List[str] = field(default_factory=list)
    体用: HerbTiYong = field(default_factory=lambda: HerbTiYong(0.0, 0.0))
    君臣佐使: str = ""
    功效: str = ""


@dataclass
class FormulaData:
    组成: List[Tuple[str, int]] = field(default_factory=list)
    君: List[str] = field(default_factory=list)
    臣: List[str] = field(default_factory=list)
    佐: List[str] = field(default_factory=list)
    使: List[str] = field(default_factory=list)
    功效: str = ""
    体用: HerbTiYong = field(default_factory=lambda: HerbTiYong(0.0, 0.0))
    六经: str = ""
    主治: str = ""
    方解: str = ""
    组成文本: List[str] = field(default_factory=list)


@dataclass
class SynergyRule:
    名称: str
    机理: str
    例药: str
    例方: str


@dataclass
class SynergyPair:
    化合物: str
    名称: str
    机理: str
    例方: str


