def known_formulas() -> List[str]:
    """所有已知方名列表（排序）"""
    return sorted(FORMULAS.keys())


def known_herbs() -> List[str]:
    """所有已知药名列表（排序）"""
    return sorted(HERB_WUWEI.keys())


def get_herb(name: str) -> Optional[HerbData]:
    """获取单味药数据"""
    return HERB_WUWEI.get(name)


def get_formula(name: str) -> Optional[FormulaData]:
    """获取方剂数据（先精确，再模糊匹配）"""
    if name in FORMULAS:
        return FORMULAS[name]
    matches = [k for k in FORMULAS.keys() if k in name]
    if len(matches) == 1:
        return FORMULAS[matches[0]]
    return None


def _synthesize_tiyong(herbs: List[str]) -> HerbTiYong:
    """合成体用坐标（加权平均）"""
    sum_ti = 0.0
    sum_yong = 0.0
    count = 0
    for h in herbs:
        data = HERB_WUWEI.get(h)
        if data:
            sum_ti += data.体用.ti
            sum_yong += data.体用.yong
            count += 1
    if count == 0:
        return HerbTiYong(0.0, 0.0)
    return HerbTiYong(
        ti=round(sum_ti / count * 100.0) / 100.0,
        yong=round(sum_yong / count * 100.0) / 100.0,
    )


def _tiyong_angle(a: HerbTiYong, b: HerbTiYong) -> float:
    """两个体用向量的夹角"""
    dot = a.ti * b.ti + a.yong * b.yong
    norm_a = math.sqrt(a.ti * a.ti + a.yong * a.yong)
    norm_b = math.sqrt(b.ti * b.ti + b.yong * b.yong)
    if norm_a == 0.0 or norm_b == 0.0:
        return 0.0
    cos = max(-1.0, min(1.0, dot / (norm_a * norm_b)))
    return round(math.degrees(math.acos(cos)) * 100.0) / 100.0


def _detect_synergy(herbs: List[str]) -> List[SynergyPair]:
    """检测五味化合对"""
    detected: List[SynergyPair] = []
    seen = set()
    n = len(herbs)
    for i in range(n):
        h1 = herbs[i]
        f1 = HERB_WUWEI.get(h1)
        if f1 is None:
            continue
        for h2 in herbs[i + 1:]:
            f2 = HERB_WUWEI.get(h2)
            if f2 is None:
                continue
            for (wf1, wf2), rule in WUWEI_SYNERGY_RULES.items():
                for a in f1.五味:
                    for b in f2.五味:
                        if (a == wf1 and b == wf2) or (a == wf2 and b == wf1):
                            key = (f"{h1}({a}) + {h2}({b})", rule.名称)
                            if key not in seen:
                                seen.add(key)
                                detected.append(SynergyPair(
                                    化合物=f"{h1}({a}) + {h2}({b})",
                                    名称=rule.名称,
                                    机理=rule.机理,
                                    例方=rule.例方,
                                ))
    return detected


