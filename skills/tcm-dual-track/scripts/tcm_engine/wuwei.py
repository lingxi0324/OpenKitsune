def analyze_formula(formula_name: str) -> dict:
    """全维方剂分析"""
    formula_name = CLASSIC_ALIASES.get(formula_name, formula_name)
    if formula_name in FORMULAS:
        matched_name = formula_name
        fx = FORMULAS[formula_name]
    else:
        known = known_formulas()
        fuzzy = [k for k in known if formula_name in k]
        if len(fuzzy) == 1:
            matched_name = fuzzy[0]
            fx = FORMULAS[matched_name]
        elif len(fuzzy) > 1:
            return {"错误": f"方剂「{formula_name}」存在多个匹配: {fuzzy}，请精确指定"}
        else:
            sample = "、".join(known[:12])
            return {"错误": f"方剂「{formula_name}」未在数据库中找到（共 {len(known)} 首，例：{sample}…）"}

    herbs = [h for (h, _) in fx.组成]

    # 1. 五味统计
    wuwei_counter: Dict[str, int] = {}
    for h in herbs:
        data = HERB_WUWEI.get(h)
        if data:
            for w in data.五味:
                wuwei_counter[w] = wuwei_counter.get(w, 0) + 1

    # 2. 性味统计
    xing_counter: Dict[str, int] = {}
    for h in herbs:
        data = HERB_WUWEI.get(h)
        if data:
            xing_counter[data.性] = xing_counter.get(data.性, 0) + 1

    # 3. 归经统计
    guijing_counter: Dict[str, int] = {}
    for h in herbs:
        data = HERB_WUWEI.get(h)
        if data:
            for j in data.归经:
                guijing_counter[j] = guijing_counter.get(j, 0) + 1

    # 4. 体用合成
    tiyong = _synthesize_tiyong(herbs)

    # 5. 君臣佐使
    junchen_zuoshi = {
        "君": list(fx.君),
        "臣": list(fx.臣),
        "佐": list(fx.佐),
        "使": list(fx.使),
    }

    # 6. 五味化合
    synergy_pairs = _detect_synergy(herbs)

    return {
        "名称": matched_name,
        "组成": fx.组成文本 or [f"{h} {d}g" for (h, d) in fx.组成],
        "功效": fx.功效,
        "主治": fx.主治,
        "方解": fx.方解,
        "君臣佐使": junchen_zuoshi,
        "五味分析": wuwei_counter,
        "性味统计": xing_counter,
        "归经统计": guijing_counter,
        "体用坐标": {"体": tiyong.ti, "用": tiyong.yong},
        "六经": fx.六经,
        "五味化合": [
            {"化合物": p.化合物, "名称": p.名称, "机理": p.机理, "例方": p.例方}
            for p in synergy_pairs
        ],
    }


def compare_formulas(f1_name: str, f2_name: str) -> dict:
    """两方对比分析"""
    r1 = analyze_formula(f1_name)
    r2 = analyze_formula(f2_name)

    if "错误" in r1 or "错误" in r2:
        err = r1.get("错误") or r2.get("错误")
        return {"错误": f"对比失败: {err}"}

    herbs1 = set(c.split(" ")[0] for c in r1["组成"])
    herbs2 = set(c.split(" ")[0] for c in r2["组成"])

    common = sorted(herbs1 & herbs2)
    only1 = sorted(herbs1 - herbs2)
    only2 = sorted(herbs2 - herbs1)

    ww1 = r1["五味分析"]
    ww2 = r2["五味分析"]
    wuwei_diff: Dict[str, tuple] = {}
    for w in set(ww1.keys()) | set(ww2.keys()):
        v1 = ww1.get(w, 0)
        v2 = ww2.get(w, 0)
        if v1 != v2:
            wuwei_diff[w] = (v1, v2)

    ty1_ti = r1["体用坐标"]["体"]
    ty1_yong = r1["体用坐标"]["用"]
    ty2_ti = r2["体用坐标"]["体"]
    ty2_yong = r2["体用坐标"]["用"]
    ty1 = HerbTiYong(ty1_ti, ty1_yong)
    ty2 = HerbTiYong(ty2_ti, ty2_yong)

    return {
        "对比方": [f1_name, f2_name],
        "功效对比": {"方1": r1["功效"], "方2": r2["功效"]},
        "六经对比": {"方1": r1["六经"], "方2": r2["六经"]},
        "组成差异": {
            "共有": common,
            "方1独有": only1,
            "方2独有": only2,
        },
        "君臣对比": {"方1": r1["君臣佐使"], "方2": r2["君臣佐使"]},
        "五味差异": wuwei_diff,
        "体用差异": {
            "体差异": round(ty1_ti * 100.0 - ty2_ti * 100.0) / 100.0,
            "用差异": round(ty1_yong * 100.0 - ty2_yong * 100.0) / 100.0,
            "向量夹角": _tiyong_angle(ty1, ty2),
        },
        "体用坐标": {"方1": {"体": ty1_ti, "用": ty1_yong},
                   "方2": {"体": ty2_ti, "用": ty2_yong}},
        "五味化合对比": {"方1": r1["五味化合"], "方2": r2["五味化合"]},
    }


def wuwei_synergy(herbs_list: List[str]) -> List[SynergyPair]:
    """五味化合交互分析"""
    return _detect_synergy(herbs_list)


def formula_tiyong(formula_name: str) -> dict:
    """方剂体用坐标映射"""
    if formula_name in FORMULAS:
        matched_name = formula_name
        fx = FORMULAS[formula_name]
    else:
        known = known_formulas()
        fuzzy = [k for k in known if formula_name in k]
        if len(fuzzy) == 1:
            matched_name = fuzzy[0]
            fx = FORMULAS[matched_name]
        elif len(fuzzy) > 1:
            return {"错误": f"方剂「{formula_name}」存在多个匹配: {fuzzy}"}
        else:
            return {"错误": f"方剂「{formula_name}」未找到"}

    herbs = [h for (h, _) in fx.组成]
    tiyong = _synthesize_tiyong(herbs)

    herb_tiyong = []
    for h in herbs:
        data = HERB_WUWEI.get(h)
        if data:
            herb_tiyong.append((h, {"体": data.体用.ti, "用": data.体用.yong}))

    if tiyong.ti >= 0.0 and tiyong.yong >= 0.0:
        quadrant = "第一象限: 体用俱足（补益/调和）"
    elif tiyong.ti < 0.0 and tiyong.yong >= 0.0:
        quadrant = "第二象限: 体损用亢（解表/理气/温里）"
    elif tiyong.ti < 0.0 and tiyong.yong < 0.0:
        quadrant = "第三象限: 体用俱损（清热/泻下/祛湿）"
    else:
        quadrant = "第四象限: 体足用弱（养阴/收敛/安神）"

    return {
        "名称": matched_name,
        "体用坐标": {"体": tiyong.ti, "用": tiyong.yong},
        "象限": quadrant,
        "组成体用分布": herb_tiyong,
    }


def analyze_recommended_formulas(formula_names: List[str]) -> List[dict]:
    """分析 liujing 推荐方列表，返回每方体用坐标"""
    results = []
    for name in formula_names:
        result = analyze_formula(name)
        if "错误" not in result:
            results.append(result)
    return results
