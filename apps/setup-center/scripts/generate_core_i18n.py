def load_translation_files():
    """Load extra section translations from scripts/translations/<lang>.py.

    Each file must define:
      LANG  = "xx"
      EXTRA = {"config": {...}, ...}   # sections merged on top of T
    """
    merged = {}
    for f in sorted(SCRIPTS.glob("translations/*.py")):
        spec = importlib.util.spec_from_file_location(f.stem, f)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        merged.setdefault(mod.LANG, {}).update(mod.EXTRA)
    return merged


def fill_leaf(template, trans, path, missing):
    """Mirror template structure; leaves must exist in trans."""
    if isinstance(template, dict):
        out = {}
        for k, v in template.items():
            if isinstance(v, dict):
                out[k] = fill_leaf(v, trans.get(k, {}), path + [k], missing)
            else:
                if k not in trans:
                    missing.append(".".join(path + [k]))
                    out[k] = v  # keep zh value as fallback marker
                else:
                    out[k] = trans[k]
        return out
    return trans


def main():
    langs = ["hi", "es", "ar", "fr", "bn", "pt", "ru"]
    extras = load_translation_files()
    ok = True
    for lang in langs:
        data = dict(T[lang])
        data.update(extras.get(lang, {}))
        missing = []
        out = {}
        for sec, template in zh.items():
            if sec not in data:
                continue  # section not translated yet -> fallback, not an error
            out[sec] = fill_leaf(template, data[sec], [sec], missing)
        if missing:
            ok = False
            print(f"[{lang}] MISSING {len(missing)}: {missing[:10]}")
        path = BASE / f"{lang}.json"
        # Russian plural forms for {{count}} endpoints (i18next plural keys)
        if lang == "ru" and "topbar" in data:
            for pk in ("endpoints_one", "endpoints_few", "endpoints_many"):
                if pk in data["topbar"]:
                    out.setdefault("topbar", {})[pk] = data["topbar"][pk]
        with open(path, "w", encoding="utf-8") as f:
            json.dump(out, f, ensure_ascii=False, indent=2)
            f.write("\n")
        total = sum(1 for _ in iter_leaves(out))
        print(f"[{lang}] written -> {path.name} ({total} leaf strings)")
    sys.exit(0 if ok else 1)


def iter_leaves(o):
    if isinstance(o, dict):
        for v in o.values():
            yield from iter_leaves(v)
    else:
        yield o


if __name__ == "__main__":
    main()
